/**
 * KNSDC WhatsApp Bulk Sender (No API Key - Uses WhatsApp Web automation)
 * 
 * Reads participants from the local sync server (server.js on port 3000)
 * and automatically sends registration confirmation messages via WhatsApp Web.
 * 
 * Requirements:
 *   - Node.js installed
 *   - npm install puppeteer
 *   - Your WhatsApp account (QR scan on first run)
 */

import puppeteer from 'puppeteer';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import https from 'https';
import http from 'http';
import { URL } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// ---- CONFIGURATION ----
const DELAY_BETWEEN_MSGS = parseInt(process.env.WA_DELAY || '12000', 10); // 12s default
const PROFILE_DIR = path.join(__dirname, '.wa-profile'); // Saves login session
const MAX_RETRIES = 2;

// ---- Helpers ----
const sleep = (ms) => new Promise(r => setTimeout(r, ms));

function log(msg) {
    const ts = new Date().toLocaleTimeString();
    console.log(`[${ts}] ${msg}`);
}

function normalizePhone(phone) {
    let digits = String(phone || '').replace(/\D/g, '');
    if (digits.length === 10) digits = '91' + digits; // India country code
    if (digits.length === 11 && digits.startsWith('0')) digits = '91' + digits.slice(1);
    return digits; // returns full international number without '+'
}

// ---- Download image helper ----
function downloadFile(urlStr, dest) {
    return new Promise((resolve, reject) => {
        try {
            const parsedUrl = new URL(urlStr);
            const client = parsedUrl.protocol === 'https:' ? https : http;
            const request = client.get(urlStr, (response) => {
                if (response.statusCode === 200) {
                    const file = fs.createWriteStream(dest);
                    response.pipe(file);
                    file.on('finish', () => {
                        file.close();
                        resolve(dest);
                    });
                    file.on('error', (err) => {
                        fs.unlink(dest, () => {});
                        reject(err);
                    });
                } else {
                    reject(new Error(`Failed to download: HTTP ${response.statusCode}`));
                }
            });
            request.on('error', (err) => {
                fs.unlink(dest, () => {});
                reject(err);
            });
        } catch (err) {
            reject(err);
        }
    });
}

// ---- Load participants from wa-bulk-jobs.json (generated by Monitor page) ----
async function loadJobs() {
    const jobsFile = path.join(__dirname, 'wa-bulk-jobs.json');
    if (!fs.existsSync(jobsFile)) {
        throw new Error('wa-bulk-jobs.json not found. Open KNSDC-Monitor.html → Registration → 🚀 Auto Bulk Send → click "📥 Download Send File" first.');
    }
    const jobs = JSON.parse(fs.readFileSync(jobsFile, 'utf8'));
    log(`Loaded ${jobs.recipients?.length || 0} recipients from wa-bulk-jobs.json (event: ${jobs.eventName || 'Unknown'})`);
    return jobs.recipients || [];
}

// ---- Open chat and send message/media via WhatsApp Web UI ----
async function sendWhatsAppMessage(page, phone, message, localBannerPath = null) {
    const fullPhone = phone.startsWith('91') ? phone : '91' + phone;
    const waLink = `https://web.whatsapp.com/send?phone=${fullPhone}`;

    await page.goto(waLink, { waitUntil: 'domcontentloaded', timeout: 45000 });
    await sleep(4000);

    // Wait for the message input box (signifies page is loaded)
    const inputSelector = 'div[contenteditable="true"][data-tab="10"]';
    await page.waitForSelector(inputSelector, { timeout: 35000 });
    await sleep(2000);

    if (localBannerPath && fs.existsSync(localBannerPath)) {
        log(`📸 Uploading image banner...`);
        // Find file input
        const fileInput = await page.waitForSelector('input[type="file"]', { timeout: 15000 });
        await fileInput.uploadFile(localBannerPath);
        await sleep(3000);

        // Wait for preview screen caption input
        const captionSelector = 'div[contenteditable="true"]';
        await page.waitForSelector(captionSelector, { timeout: 15000 });
        await sleep(1000);

        // Type the message into the caption input
        await page.evaluate((msg) => {
            const inputs = document.querySelectorAll('div[contenteditable="true"]');
            let captionInput = Array.from(inputs).find(el => el.getAttribute('data-tab') !== '10') || inputs[0];
            if (captionInput) {
                captionInput.focus();
                document.execCommand('insertText', false, msg);
            }
        }, message);
        await sleep(1500);

        // Click send button
        const sendBtnSelector = 'span[data-icon="send"], div[data-testid="send"]';
        const sendBtn = await page.waitForSelector(sendBtnSelector, { timeout: 10000 });
        await sendBtn.click();
        await sleep(4000);
    } else {
        // Fallback to text-only send
        log(`✍️ Sending text-only message...`);
        await page.click(inputSelector);
        await page.evaluate(() => {
            const el = document.querySelector('div[contenteditable="true"][data-tab="10"]');
            el.focus();
        });
        await sleep(500);

        await page.evaluate((msg) => {
            const el = document.querySelector('div[contenteditable="true"][data-tab="10"]');
            el.focus();
            document.execCommand('insertText', false, msg);
        }, message);

        await sleep(800);
        await page.keyboard.press('Enter');
        await sleep(2000);
    }

    // Verify the message was sent (check for outgoing message checks)
    const sentCheck = await page.evaluate(() => {
        const outgoing = document.querySelectorAll('div.message-out');
        if (outgoing.length === 0) return false;
        const last = outgoing[outgoing.length - 1];
        return !!last.querySelector('span[data-icon*="check"], span[data-icon*="msg"]');
    });

    return sentCheck;
}

// ---- Main WhatsApp sending logic ----
async function main() {
    console.log('══════════════════════════════════════════════════');
    console.log('🚀 KNSDC WhatsApp Bulk Sender (No API Key)');
    console.log('══════════════════════════════════════════════════');
    log('Source: wa-bulk-jobs.json (no server needed)');
    log(`Delay between messages: ${DELAY_BETWEEN_MSGS / 1000}s`);

    let participants;
    try {
        participants = await loadJobs();
    } catch (e) {
        console.error('❌ ' + e.message);
        process.exit(1);
    }

    if (participants.length === 0) {
        console.error('❌ No participants with phone numbers found.');
        process.exit(1);
    }

    console.log(`\n📋 Participants to message: ${participants.length}`);
    console.log('   (Press Ctrl+C anytime to cancel)\n');

    // Launch browser - VISIBLE window (required for QR scan on first use)
    log('🌐 Launching WhatsApp Web in a visible window...');
    const browser = await puppeteer.launch({
        headless: false, // MUST be false so you can scan QR code
        userDataDir: PROFILE_DIR, // Saves login session
        args: [
            '--no-sandbox',
            '--disable-setuid-sandbox',
            '--disable-dev-shm-usage',
            '--window-size=1400,900',
        ],
        defaultViewport: { width: 1400, height: 900 },
    });

    const page = await browser.newPage();
    await page.setUserAgent('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36');

    try {
        log('⏳ Opening web.whatsapp.com...');
        await page.goto('https://web.whatsapp.com/', { waitUntil: 'domcontentloaded', timeout: 60000 });

        // Wait for login QR or main UI
        await sleep(5000);
        log('⏳ Waiting for WhatsApp to load...');

        // Check if QR code is needed by waiting for either QR canvas or main chat list
        await page.waitForFunction(() => {
            const qr = document.querySelector('canvas[aria-label*="Scan"]') ||
                document.querySelector('canvas[aria-label*="QR"]') ||
                document.querySelector('canvas[aria-label*="qr code"]') ||
                document.querySelector('div[data-testid="qrcode"]');
            const main = document.querySelector('#pane-side') ||
                document.querySelector('div[data-testid="chat-list"]');
            return !!(qr || main);
        }, { timeout: 60000 });

        const hasQR = await page.evaluate(() => {
            return !!(document.querySelector('canvas[aria-label*="Scan"]') ||
                document.querySelector('canvas[aria-label*="QR"]') ||
                document.querySelector('canvas[aria-label*="qr code"]') ||
                document.querySelector('div[data-testid="qrcode"]'));
        });

        if (hasQR) {
            console.log('\n📱 ═══════════════════════════════════════════════════');
            console.log('📱  🔴 ACTION REQUIRED: SCAN THE QR CODE');
            console.log('📱  ─────────────────────────────────────────────');
            console.log('📱  1. Open WhatsApp on your phone');
            console.log('📱  2. Go to Settings → Linked Devices');
            console.log('📱  3. Tap "Link a Device"');
            console.log('📱  4. Scan the QR code shown in the browser window');
            console.log('📱  ─────────────────────────────────────────────');
            console.log('📱  Waiting for scan... (session saved for next time)');
            console.log('📱 ═══════════════════════════════════════════════════\n');

            // Wait until QR is gone (user scanned)
            await page.waitForFunction(() => {
                return !!document.querySelector('#pane-side') ||
                    !!document.querySelector('div[data-testid="chat-list"]');
            }, { timeout: 180000 });

            log('✅ WhatsApp Web logged in! Session saved. Next runs won\'t need QR.\n');
            await sleep(3000);
        } else {
            log('✅ Already logged in (session saved from previous run).\n');
        }

        // Start the Live HTTP Server for real-time 1-click stage alerts from Monitor Portal
        startHttpServer(page);

        // Check if there are bulk jobs to run
        const jobsFile = path.join(__dirname, 'wa-bulk-jobs.json');
        if (fs.existsSync(jobsFile)) {
            const participants = await loadJobs();
            if (participants && participants.length > 0) {
                // Results tracking
                let sent = 0;
                let failed = 0;
                let skipped = 0;
                const failedList = [];

                log(`📤 Sending to ${participants.length} participants from wa-bulk-jobs.json...\n`);

                for (let i = 0; i < participants.length; i++) {
                    const p = participants[i];
                    log(`(${i + 1}/${participants.length}) 📨 Sending to ${p.name} (${p.phone})...`);

                    let localBannerPath = null;
                    if (p.banner) {
                        try {
                            let ext = '.jpg';
                            try {
                                const parsed = new URL(p.banner);
                                ext = path.extname(parsed.pathname) || '.jpg';
                            } catch (_) {}
                            
                            const tempDest = path.join(__dirname, `temp_banner_${Date.now()}${ext}`);
                            await downloadFile(p.banner, tempDest);
                            localBannerPath = tempDest;
                        } catch (err) {
                            log(`   ⚠️ Could not download banner: ${err.message}. Falling back to text-only.`);
                        }
                    }

                    let success = false;
                    for (let attempt = 0; attempt <= MAX_RETRIES && !success; attempt++) {
                        try {
                            if (attempt > 0) {
                                log(`   🔄 Retry ${attempt} for ${p.name}...`);
                                await sleep(5000);
                            }

                            const confirmed = await sendWhatsAppMessage(page, p.phone, p.message, localBannerPath);
                            if (confirmed) {
                                log(`   ✅ Sent to ${p.name}`);
                                success = true;
                                sent++;
                            } else {
                                log(`   ⚠️ Message entered - marking as sent`);
                                success = true;
                                sent++;
                            }
                        } catch (e) {
                            const errMsg = e.message?.slice(0, 150) || String(e);
                            log(`   ❌ Error: ${errMsg}`);
                            if (attempt >= MAX_RETRIES) {
                                failed++;
                                failedList.push(`${p.name} (${p.phone}) - ${errMsg.slice(0, 80)}`);
                            }
                        }
                    }

                    if (localBannerPath && fs.existsSync(localBannerPath)) {
                        try { fs.unlinkSync(localBannerPath); } catch (_) {}
                    }

                    if (i < participants.length - 1) {
                        log(`   ⏱️ Waiting ${DELAY_BETWEEN_MSGS / 1000}s before next...`);
                        await sleep(DELAY_BETWEEN_MSGS);
                    }
                }

                console.log('\n══════════════════════════════════════════════════');
                console.log('📊 BULK SEND COMPLETE');
                console.log('══════════════════════════════════════════════════');
                console.log(`   ✅ Sent:     ${sent}`);
                console.log(`   ❌ Failed:   ${failed}`);
                console.log(`   ⏭️ Skipped:  ${skipped}`);
                console.log('══════════════════════════════════════════════════\n');
            }
        }

        console.log('⚡ WhatsApp Bot is READY and waiting for Live Stage Alerts from KNSDC Monitor portal.');
        console.log('   (Keep this window running during the event!)\n');

    } catch (e) {
        console.error('\n❌ Fatal error: ' + e.message);
        if (e.message.includes('Timed out')) {
            console.error('   The WhatsApp page took too long. Check your internet connection and try again.');
        }
    }
}

// ---- HTTP SERVER FOR REAL-TIME STAGE CALLS FROM MONITOR PORTAL ----
function startHttpServer(page) {
    const server = http.createServer(async (req, res) => {
        // Enable CORS
        res.setHeader('Access-Control-Allow-Origin', '*');
        res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
        res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

        if (req.method === 'OPTIONS') {
            res.writeHead(204);
            res.end();
            return;
        }

        if (req.url === '/health' && req.method === 'GET') {
            res.writeHead(200, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({ status: 'ok', service: 'knsdc-whatsapp-bot' }));
            return;
        }

        if (req.url === '/send-stage-alert' && req.method === 'POST') {
            let body = '';
            req.on('data', chunk => { body += chunk.toString(); });
            req.on('end', async () => {
                try {
                    const data = JSON.parse(body);
                    const { phone, message, bannerPath } = data;
                    if (!phone || !message) {
                        res.writeHead(400, { 'Content-Type': 'application/json' });
                        res.end(JSON.stringify({ error: 'Missing phone or message' }));
                        return;
                    }

                    log(`📲 Received Live Stage Alert request for ${phone}...`);
                    
                    let localBanner = bannerPath ? path.resolve(__dirname, bannerPath) : null;
                    if (!localBanner || !fs.existsSync(localBanner)) {
                        const defaultBanner = path.join(__dirname, 'cultural', 'photo_6118659175400280599_y.jpg');
                        localBanner = fs.existsSync(defaultBanner) ? defaultBanner : null;
                    }

                    const sent = await sendWhatsAppMessage(page, phone, message, localBanner);
                    res.writeHead(200, { 'Content-Type': 'application/json' });
                    res.end(JSON.stringify({ success: sent, phone }));
                } catch (err) {
                    res.writeHead(500, { 'Content-Type': 'application/json' });
                    res.end(JSON.stringify({ error: err.message }));
                }
            });
            return;
        }

        res.writeHead(404, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: 'Not found' }));
    });

    const PORT = 3050;
    server.listen(PORT, () => {
        console.log(`\n🚀 [WhatsApp Bot Server] Listening for 1-Click Stage Alerts on http://localhost:${PORT}`);
        console.log(`   Keep this terminal open while managing the event!\n`);
    });
}

main();